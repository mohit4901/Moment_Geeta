export function dt(key, lang = 'hi') {
  const entry = DIET_UI[key];
  if (!entry) return key;
  if (entry[lang]) return entry[lang];
  if (lang === 'en') return entry.en || entry.hi || key;
  if (['as', 'mni'].includes(lang)) return entry.as || entry.bn || entry.hi;
  if (['mai', 'doi', 'ne', 'sa', 'kok'].includes(lang)) return entry.hi || entry.en;
  if (['sd', 'ks'].includes(lang)) return entry.ur || entry.hi;
  if (['brx', 'sat'].includes(lang)) return entry.as || entry.hi;
  return entry.hi || entry.en;
}

export function resolveDietLang(lang = 'hi') {
  if (lang === 'en') return 'en';
  if (['hi', 'mai', 'doi', 'ne', 'sa', 'kok'].includes(lang)) return 'hi';
  return lang;
}

